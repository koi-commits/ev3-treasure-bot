"""Export tap-probe GRU weights to dependency-free MicroPython constants."""

from __future__ import annotations

import argparse
import importlib
import json
import os
import sys
import time

import numpy as np
import torch

from .tap_event_train import TapSeatGRU

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")


def _literal(value):
    if isinstance(value, list):
        return "[" + ",".join(_literal(v) for v in value) + "]"
    return "{:.7g}".format(float(value))


def export(checkpoint, output):
    payload = torch.load(checkpoint, map_location="cpu", weights_only=False)
    state = payload["state_dict"]
    fields = {
        "INPUT_SIZE": len(payload["features"]),
        "HIDDEN_SIZE": payload["hidden_size"],
        "THRESHOLD": payload["threshold"], "DEBOUNCE_N": 1,
        "W_IH": state["gru.weight_ih"].tolist(),
        "W_HH": state["gru.weight_hh"].tolist(),
        "B_IH": state["gru.bias_ih"].tolist(),
        "B_HH": state["gru.bias_hh"].tolist(),
        "W_OUT": state["head.weight"][0].tolist(),
        "B_OUT": state["head.bias"][0].item(),
    }
    lines = ["# Generated by learning/export_tap_probe.py; do not hand edit."]
    for key, value in fields.items():
        if isinstance(value, int):
            lines.append("{} = {}".format(key, value))
        else:
            lines.append("{} = {}".format(key, _literal(value)))
    with open(output, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    if SRC not in sys.path:
        sys.path.insert(0, SRC)
    name = os.path.splitext(os.path.basename(output))[0]
    sys.modules.pop(name, None)
    weights = importlib.import_module(name)
    from contact_inference import ContactInference
    runtime = ContactInference(weights)
    model = TapSeatGRU(payload["hidden_size"], len(payload["features"]))
    model.load_state_dict(state)
    model.eval()
    rng = np.random.default_rng(456)
    sample = rng.normal(size=(75, len(payload["features"]))).astype(np.float32)
    hidden = torch.zeros(1, payload["hidden_size"])
    errors = []
    for row in sample:
        with torch.no_grad():
            hidden = model.gru(torch.from_numpy(row).unsqueeze(0), hidden)
            ref = torch.sigmoid(model.head(hidden)).item()
        got, _ = runtime.update(row.tolist())
        errors.append(abs(ref - got))
    t0 = time.perf_counter()
    for _ in range(10000):
        runtime.update(sample[0].tolist())
    report = {
        "max_probability_error": max(errors),
        "cpython_us_per_step": (time.perf_counter() - t0) * 1e6 / 10000,
        "weight_module_bytes": os.path.getsize(output),
        "parameters": sum(v.numel() for v in state.values()),
    }
    report_path = os.path.splitext(checkpoint)[0] + "_export.json"
    with open(report_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, sort_keys=True)
    print(json.dumps(report, indent=2, sort_keys=True))
    return report


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--checkpoint", default=os.path.join(ROOT, "models", "tap_probe_gru_v1.pt"))
    p.add_argument("--output", default=os.path.join(SRC, "tap_probe_weights.py"))
    args = p.parse_args()
    export(args.checkpoint, args.output)


if __name__ == "__main__":
    main()

