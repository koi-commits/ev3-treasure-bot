"""Export trained ContactGRU to a small importable MicroPython weight module."""

from __future__ import annotations

import argparse
import importlib
import json
import os
import sys
import time

import numpy as np
import torch

from .contact_train import ContactGRU

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")


def _literal(value):
    if isinstance(value, list):
        return "[" + ",".join(_literal(v) for v in value) + "]"
    return "{:.7g}".format(float(value))


def export(checkpoint, output):
    payload = torch.load(checkpoint, map_location="cpu", weights_only=False)
    state = payload["state_dict"]
    fields = {
        "INPUT_SIZE": len(payload["features"]),
        "HIDDEN_SIZE": payload["hidden_size"],
        "THRESHOLD": payload["threshold"],
        "DEBOUNCE_N": payload["debounce_n"],
        "W_IH": state["gru.weight_ih"].tolist(),
        "W_HH": state["gru.weight_hh"].tolist(),
        "B_IH": state["gru.bias_ih"].tolist(),
        "B_HH": state["gru.bias_hh"].tolist(),
        "W_OUT": state["head.weight"][0].tolist(),
        "B_OUT": state["head.bias"][0].item(),
    }
    lines = ["# Generated by learning/export_contact.py; do not hand edit."]
    for key, value in fields.items():
        if isinstance(value, int):
            lines.append("{} = {}".format(key, value))
        else:
            lines.append("{} = {}".format(key, _literal(value)))
    with open(output, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    if SRC not in sys.path:
        sys.path.insert(0, SRC)
    module_name = os.path.splitext(os.path.basename(output))[0]
    sys.modules.pop(module_name, None)
    weights = importlib.import_module(module_name)
    from contact_inference import ContactInference
    runtime = ContactInference(weights)
    model = ContactGRU(payload["hidden_size"])
    model.load_state_dict(state)
    model.eval()
    rng = np.random.default_rng(123)
    samples = rng.normal(size=(100, len(payload["features"]))).astype(np.float32)
    hidden = torch.zeros(1, payload["hidden_size"])
    errors = []
    for sample in samples:
        with torch.no_grad():
            hidden = model.gru(torch.from_numpy(sample).unsqueeze(0), hidden)
            ref = torch.sigmoid(model.head(hidden)).item()
        got, _ = runtime.update(sample.tolist())
        errors.append(abs(ref - got))
    t0 = time.perf_counter()
    for _ in range(10000):
        runtime.update(samples[0].tolist())
    us = (time.perf_counter() - t0) * 1e6 / 10000
    report = {"max_probability_error": max(errors), "cpython_us_per_step": us,
              "weight_module_bytes": os.path.getsize(output),
              "parameters": sum(v.numel() for v in state.values())}
    print(json.dumps(report, indent=2, sort_keys=True))
    return report


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--checkpoint", default=os.path.join(ROOT, "models", "contact_gru.pt"))
    p.add_argument("--output", default=os.path.join(SRC, "contact_weights.py"))
    args = p.parse_args()
    export(args.checkpoint, args.output)


if __name__ == "__main__":
    main()

